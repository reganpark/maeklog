#!/usr/bin/env python3
"""Exercise a patched TUI against a separate official shared app-server and Herdr."""
import argparse
import http.server
import json
import os
from pathlib import Path
import shlex
import subprocess
import tempfile
import threading
import time
from codex_hook_trust import approved_hooks, installation_paths


parser = argparse.ArgumentParser()
parser.add_argument('--binary', required=True)
parser.add_argument('--server-binary', required=True)
parser.add_argument('--pane', required=True)
parser.add_argument('--root', required=True)
parser.add_argument('--pm-binary', type=Path,
                    default=installation_paths()[0] / 'bin/maeklog-hook')
parser.add_argument('--default-bridge', action='store_true',
                    help='Use the installed default bridge path instead of the diagnostic wrapper')
args = parser.parse_args()
if os.environ.get('HERDR_ENV') != '1':
    parser.error('Run the live test from a Herdr-managed terminal')
root = Path(args.root)
root.mkdir(mode=0o700)
home = root / 'codex-home'
home.mkdir(mode=0o700)
state = root / 'state'
state.mkdir(mode=0o700)
repo = root / 'repo'
repo.mkdir()
registry_path = state / 'client-routing.json'
registry_path.write_text('{"clients":[],"turns":{}}')
pm = args.pm_binary.resolve()
bridge = root / 'client-bridge'
bridge_log = root / 'client-bridge.log'
bridge.write_text('#!/bin/sh\n'
                  + 'printf "%s\\n" "$*" >> ' + shlex.quote(str(bridge_log)) + '\n'
                  + 'exec ' + shlex.quote(str(pm)) + ' "$@" >> '
                  + shlex.quote(str(bridge_log)) + ' 2>&1\n')
bridge.chmod(0o700)
requests = []


class Model(http.server.BaseHTTPRequestHandler):
    def log_message(self, *unused):
        pass

    def do_POST(self):
        body = json.loads(self.rfile.read(int(self.headers['Content-Length'])))
        title = body.get('metadata', {}).get('thread_source') in {'system', 'thread_title'} or any(
            part.get('text', '').startswith('Generate a concise, single-line task title')
            for item in body.get('input', []) if item.get('role') == 'user'
            for part in item.get('content', []))
        text = '{"title":"PM upgrade smoke"}' if title else 'PM_UPGRADE_REPLY'
        requests.append({'path': self.path, 'model': body.get('model'), 'title': title})
        events = [
            {'type': 'response.created', 'response': {'id': 'pm-smoke-response'}},
            {'type': 'response.output_item.done', 'item': {'type': 'message', 'role': 'assistant',
             'id': 'pm-smoke-message', 'content': [{'type': 'output_text', 'text': text}]}},
            {'type': 'response.completed', 'response': {'id': 'pm-smoke-response',
             'usage': {'input_tokens': 0, 'input_tokens_details': None, 'output_tokens': 0,
                       'output_tokens_details': None, 'total_tokens': 0}}},
        ]
        payload = ''.join('event: ' + e['type'] + '\ndata: ' + json.dumps(e) + '\n\n' for e in events).encode()
        self.send_response(200)
        self.send_header('Content-Type', 'text/event-stream')
        self.send_header('Content-Length', str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)


model = http.server.ThreadingHTTPServer(('127.0.0.1', 0), Model)
threading.Thread(target=model.serve_forever, daemon=True).start()
# Copy only the existing PM handler definitions and their approved hashes. No auth,
# other plugins, global config, or user conversation is copied into the fixture.
installed_binary, original_approved = approved_hooks()
if installed_binary.resolve() != pm:
    raise RuntimeError('Live fixture must use the installed, manually approved Maeklog hook binary')
hooks = {}
trust_config = ''
# Match the exact installed command generated by Maeklog's hook installer.
for event, key in [('SessionStart', 'session_start'), ('UserPromptSubmit', 'user_prompt_submit'),
                   ('Stop', 'stop'), ('Interrupt', 'interrupt')]:
    approved = original_approved[event]
    group, handler = approved['group'], approved['handler']
    trusted = approved['trusted_hash']
    hooks[event] = [{**group, 'hooks': [handler]}]
    new_key = f'{home}/hooks.json:{key}:0:0'
    trust_config += f'\n[hooks.state.{json.dumps(new_key)}]\nenabled = true\ntrusted_hash = {json.dumps(trusted)}\n'
(home / 'hooks.json').write_text(json.dumps({'hooks': hooks}))
(home / 'config.toml').write_text(f'''model = "gpt-6-luna"
model_provider = "pm_fixture"
approval_policy = "never"
sandbox_mode = "read-only"
suppress_unstable_features_warning = true
check_for_update_on_startup = false
[model_providers.pm_fixture]
name = "PM local fixture"
base_url = "http://127.0.0.1:{model.server_port}/v1"
wire_api = "responses"
requires_openai_auth = false
supports_websockets = false
[projects.{json.dumps(str(repo))}]
trust_level = "trusted"
[analytics]
enabled = false
{trust_config}
''')
socket_directory = tempfile.TemporaryDirectory(prefix='pm-codex-sock-', dir='/tmp')
socket = Path(socket_directory.name) / 'server.sock'
shared_env = {**os.environ, 'CODEX_HOME': str(home), 'MAEKLOG_STATE_DIR': str(state),
              'MAEKLOG_DISABLE_LUNA': '1', 'MAEKLOG_PLUGIN_ROOT': str(Path(__file__).resolve().parents[1])}
shared_env.pop('MAEKLOG_INTERNAL', None)
# Deliberately wrong caller attribution, matching the historical shared-daemon bug.
shared_env.update(HERDR_PANE_ID='wrong-daemon-pane', HERDR_TAB_ID='wrong-daemon-tab',
                  HERDR_WORKSPACE_ID='wrong-daemon-workspace')
server_log = (root / 'server.log').open('w')
server = subprocess.Popen([args.server_binary, 'app-server', '--listen', f'unix://{socket}'],
                          env=shared_env, cwd=repo, stdout=server_log, stderr=server_log)
pane = None
thread = None
checks = []


def herdr(*arguments):
    result = subprocess.run(['herdr', *arguments], capture_output=True, text=True, timeout=15)
    if result.returncode:
        raise RuntimeError(result.stderr)
    if not result.stdout.strip().startswith('{'):
        return {'text': result.stdout}
    return json.loads(result.stdout)['result']


def until(predicate, label, timeout=45):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        value = predicate()
        if value:
            print('PASS', label, flush=True)
            checks.append(label)
            return value
        time.sleep(.5)
    raise RuntimeError('Timed out: ' + label)


def registry():
    return json.loads(registry_path.read_text())


def events():
    return [json.loads(line) for p in state.glob('spaces/*/inbox.jsonl')
            for line in p.read_text().splitlines() if line]


def command(text):
    # Startup typeahead intentionally discards buffered action keys. Wait for
    # the recognized agent to settle before sending Enter to its composer.
    until(lambda: herdr('pane', 'get', pane)['pane'].get('agent_status') in {'idle', 'done'},
          'TUI ready for ' + text)
    time.sleep(.5)
    herdr('pane', 'send-text', pane, text)
    time.sleep(.25)
    herdr('pane', 'send-keys', pane, 'enter')


def launch(resume=None):
    environment = {'CODEX_HOME': str(home), 'MAEKLOG_STATE_DIR': str(state),
                   'MAEKLOG_DISABLE_LUNA': '1',
                   'MAEKLOG_PLUGIN_ROOT': str(Path(__file__).resolve().parents[1])}
    # New panes inherit their shell environment from Herdr's host process, not
    # this test process. Carry the isolated home/config explicitly so the native
    # default bridge cannot accidentally select the host's installed adapter.
    environment['HOME'] = str(Path.home())
    for key in ['XDG_CONFIG_HOME', 'XDG_DATA_HOME', 'XDG_CACHE_HOME', 'XDG_STATE_HOME',
                'HERDR_PLUGIN_CONFIG_DIR']:
        if key in os.environ:
            environment[key] = os.environ[key]
    if not args.default_bridge:
        environment['MAEKLOG_CLIENT_BIN'] = str(bridge)
    argv = ['env', '-u', 'MAEKLOG_CLIENT_BIN', *[f'{k}={v}' for k,v in environment.items()], args.binary,
            '--remote', f'unix://{socket}', '--no-alt-screen', '-C', str(repo)]
    if resume:
        argv.extend(['resume', resume])
    herdr('pane', 'run', pane, shlex.join(argv))


try:
    until(socket.exists, 'isolated official shared server started')
    layout = herdr('pane', 'layout', '--pane', args.pane)['layout']
    rect = next(p['rect'] for p in layout['panes'] if p['pane_id'] == args.pane)
    direction = 'right' if rect['width'] >= 2 * rect['height'] else 'down'
    created = herdr('pane', 'split', '--pane', args.pane, '--direction', direction,
                    '--cwd', str(repo), '--no-focus')
    pane = created['pane']['pane_id']
    (root / 'pane.json').write_text(json.dumps(created))
    launch()
    until(lambda: 'Ask Codex to do anything' in herdr('pane', 'read', pane,
          '--source', 'recent-unwrapped', '--lines', '45').get('text', ''), 'new TUI ready for input')
    first = until(lambda: next(iter(registry()['clients']), None), 'new conversation registered from real terminal')
    thread = first['thread']
    expected_tab = first['route']['tab_id']
    command('PM_UPGRADE_TURN_ONE')
    until(lambda: any(e['kind'] == 'assistant_final' and e['content'] == 'PM_UPGRADE_REPLY' for e in events()),
          'actual request and final response collected through shared-server hooks')
    metas = [json.loads(p.read_text()) for p in state.glob('spaces/*/meta.json')]
    assert all(m['tab_id'] == expected_tab for m in metas)
    assert any(e['kind'] == 'user_prompt' and e['content'] == 'PM_UPGRADE_TURN_ONE' for e in events())
    checks.append('daemon environment ignored; collected into terminal tab')
    command('/new')
    until(lambda: registry()['clients'] and registry()['clients'][0]['thread'] != thread,
          'new conversation replaces registration')
    command('/quit')
    until(lambda: not registry()['clients'], 'normal exit detaches')
    until(lambda: herdr('pane','get',pane)['pane'].get('agent') != 'codex', 'shell restored')
    launch(thread)
    until(lambda: any(c['thread'] == thread for c in registry()['clients']), 'resume reattaches saved conversation')
    command('PM_UPGRADE_TURN_TWO')
    until(lambda: len([e for e in events() if e['kind'] == 'assistant_final']) >= 2,
          'resumed conversation collects next turn')
    command('/quit')
    until(lambda: not registry()['clients'], 'resumed client detaches')
    until(lambda: herdr('pane','get',pane)['pane'].get('agent') != 'codex', 'resumed shell restored')
    (root / 'result.json').write_text(json.dumps({'checks': checks, 'requests': requests,
            'event_count': len(events()), 'thread': thread, 'tab': expected_tab}, indent=2))
    print('PASS full client lifecycle', root, flush=True)
finally:
    try:
        if pane:
            (root / 'screen.json').write_text(json.dumps(herdr('pane','read',pane,'--source','recent-unwrapped','--lines','100')))
            herdr('pane','close',pane)
    finally:
        server.terminate()
        server.wait(timeout=15)
        server_log.close()
        model.shutdown()
        socket_directory.cleanup()
